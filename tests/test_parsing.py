"""Тесты для функции parse_size_text из telegram_bot.py.

Проверяют корректность разбора размеров стикеров из текстовых сообщений:
- одиночные размеры в см, мм, м ("15 см", "150 мм", "2 м")
- прямоугольные габариты ШxВ ("20x10 см", "150x90 мм", "2x1.5 м", "12х8")
- различные разделители (x, х, *, ×) и десятичные знаки (. и ,)
- невалидные строки и команды.
"""

from __future__ import annotations

import pytest

from telegram_bot import parse_size_text


@pytest.mark.parametrize(
    ("input_text", "expected"),
    [
        # Обязательные форматы из ТЗ
        ("15 см", (150.0,)),
        ("2 м", (2000.0,)),
        ("20x10 см", (200.0, 100.0)),
        ("150 мм", (150.0,)),
        # Вариации единиц измерения (латиница)
        ("15 cm", (150.0,)),
        ("150 mm", (150.0,)),
        ("2 m", (2000.0,)),
        # Дроби с точкой и запятой
        ("8.5 см", (85.0,)),
        ("8,5 см", (85.0,)),
        ("2.5 м", (2500.0,)),
        ("2,5 м", (2500.0,)),
        # Значения без явной единицы измерения (по умолчанию считаются в см)
        ("10", (100.0,)),
        ("12х8", (120.0, 80.0)),
        # Различные разделители для ШxВ (латинский x, кириллический х, *, ×)
        ("20x10 см", (200.0, 100.0)),
        ("20х10 см", (200.0, 100.0)),
        ("20*10 см", (200.0, 100.0)),
        ("20×10 см", (200.0, 100.0)),
        # Прямоугольники с миллиметрами и метрами
        ("150x90 мм", (150.0, 90.0)),
        ("2x1.5 м", (2000.0, 1500.0)),
        # Маленькие размеры не подтягиваются вверх (рамки ставит обработчик), ноль не размер
        ("0.1 мм", (0.1,)),
        ("0 см", ()),
        ("1x2 мм", (1.0, 2.0)),
    ],
)
def test_parse_size_text_valid(input_text: str, expected: tuple[float, ...]) -> None:
    """Проверка успешного парсинга валидных форматов размера."""
    assert parse_size_text(input_text) == expected


@pytest.mark.parametrize(
    "invalid_text",
    [
        "",
        "   ",
        "/start",
        "/help",
        "/admin",
        "привет",
        "хочу наклейку",
        "abc x def",
        "см",
        "мм",
        "10xx20",
    ],
)
def test_parse_size_text_invalid(invalid_text: str) -> None:
    """Невалидный ввод или команды не должны распознаваться как размер."""
    assert parse_size_text(invalid_text) == ()
